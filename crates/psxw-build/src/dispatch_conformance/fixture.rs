//! The fixture format: original MIPS images with what their symbol files
//! say, initial memory, and a short program of host loads and calls whose
//! observations are compared.
//!
//! Fixture code records effects by appending marker words to a log: a
//! pointer at `Layout::log`, then the entries. A checkpoint observes the
//! called function's `v0`/`v1` and the log.

use std::ops::Range;

/// Most log entries a fixture writes.
pub const LOG_WORDS: u32 = 48;

/// Where a fixture's pieces live. Everything is inside the reference
/// runner's scratch region (psxw-oracle `SCRATCH_BASE`), so the same
/// addresses run on both sides.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Layout {
    /// The main executable's text, then its data.
    pub main: u32,
    /// The overlay slots.
    pub slot: u32,
    pub slot2: u32,
    /// The log pointer, then `LOG_WORDS` entries.
    pub log: u32,
    /// Bytes a fixture copies or unpacks from (a file read into RAM).
    pub stage: u32,
    /// The stack the host calls with.
    pub stack: u32,
}

impl Layout {
    /// The default layout moved by `shift` bytes (a legal load address
    /// transformation).
    pub const fn at(shift: u32) -> Self {
        Self {
            main: 0x8010_0000 + shift,
            slot: 0x8011_0000 + shift,
            slot2: 0x8012_0000 + shift,
            log: 0x8013_0000 + shift,
            stage: 0x8014_0000 + shift,
            stack: 0x801B_FF00,
        }
    }

    pub fn log_range(&self) -> Range<u32> {
        self.log..self.log + 4 + 4 * LOG_WORDS
    }
}

/// One container: its original bytes and its symbol file.
#[derive(Debug, Clone)]
pub struct Image {
    pub id: String,
    pub base: u32,
    pub bytes: Vec<u8>,
    /// Bytes of code from `base`; the rest is the container's data.
    pub text: u32,
    /// What its symbol file lists: (name, address, size).
    pub funcs: Vec<(String, u32, Option<u32>)>,
    /// Decompiled C for some of its functions (the C tier). It must do what
    /// the code at those functions does.
    pub c: Option<String>,
}

impl Image {
    pub fn range(&self) -> Range<u32> {
        self.base..self.base + self.bytes.len() as u32
    }

    pub fn addr(&self, name: &str) -> u32 {
        self.funcs.iter().find(|(n, ..)| n == name).map(|f| f.1).unwrap_or_else(|| panic!("{} has no {name}", self.id))
    }
}

/// What a checkpoint must observe.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Expect {
    /// The call returns. Closed-form values where the fixture knows them;
    /// a reference run must agree in any case.
    Value { v0: Option<u32>, v1: Option<u32>, log: Option<Vec<u32>> },
    /// An explicit rejection whose diagnostic starts with `diag`, with the
    /// log as it was: no effect of an incompatible translation.
    Reject { diag: String, log: Vec<u32> },
    /// The call switches threads (ChangeThread): it is suspended with this
    /// log, until a [`Step::Resume`].
    Suspend { log: Vec<u32> },
}

impl Expect {
    pub fn v0(v0: u32, log: &[u32]) -> Self {
        Expect::Value { v0: Some(v0), v1: None, log: Some(log.to_vec()) }
    }
    pub fn reject(diag: impl Into<String>, log: &[u32]) -> Self {
        Expect::Reject { diag: diag.into(), log: log.to_vec() }
    }
}

#[derive(Debug, Clone)]
pub enum Step {
    /// The host writes bytes: a load by native code (CD DMA, the BIOS).
    Write { at: u32, bytes: Vec<u8> },
    /// The host calls a guest address (o32): a checkpoint.
    Call { entry: u32, args: [u32; 4], expect: Expect },
    /// The suspended call resumes (its thread is switched back to): a
    /// checkpoint of the same call.
    Resume { expect: Expect },
}

impl Step {
    pub fn expect(&self) -> Option<&Expect> {
        match self {
            Step::Write { .. } => None,
            Step::Call { expect, .. } | Step::Resume { expect } => Some(expect),
        }
    }
}

/// The build's expected verdict.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Build {
    Links,
    /// A compile-time rejection whose error contains this.
    Rejected(String),
}

/// Why a variant's checkpoints are judged as they are.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Evidence {
    /// Against an original-MIPS run on the reference CPU, and any
    /// closed-form values.
    Reference,
    /// Closed-form values only: the variant exercises a port-only contract
    /// (a native stand-in, a host callback, a thread switch) the original
    /// program can't express.
    ClosedForm(&'static str),
}

/// One fixture variant.
#[derive(Debug, Clone)]
pub struct Variant {
    /// D01..D10.
    pub case: &'static str,
    /// `<fixture>` or `<fixture>@<transformation>`.
    pub name: String,
    /// The seed of every generated byte (stale memory); reported.
    pub seed: u64,
    /// The support classification (phase 0): why each rejection is one.
    pub note: &'static str,
    pub evidence: Evidence,
    pub layout: Layout,
    pub main: String,
    /// In the address map's order.
    pub images: Vec<Image>,
    /// Memory at the start besides the main image: staged files, and
    /// overlay slots' prior contents.
    pub init: Vec<(u32, Vec<u8>)>,
    pub steps: Vec<Step>,
    pub build: Build,
    /// Its code switches threads (ChangeThread suspends through Asyncify).
    pub threads: bool,
    /// A proposed support/rejection rule needing operator approval. Keep
    /// observations and mismatches; agreement alone cannot approve it.
    pub review_required: Option<&'static str>,
    /// `[dispatch]` facts (TOML), as a game's manifest states them: the
    /// variant exercises explicit binding. `None`: the legacy dispatch.
    pub dispatch: Option<String>,
}

impl Variant {
    pub fn id(&self) -> String {
        format!("{}/{}", self.case, self.name)
    }

    pub fn main_image(&self) -> &Image {
        self.images.iter().find(|i| i.id == self.main).expect("a main image")
    }

    /// Whether any checkpoint expects a rejection (safety coverage).
    pub fn rejects(&self) -> bool {
        matches!(self.build, Build::Rejected(_))
            || self.steps.iter().any(|s| matches!(s.expect(), Some(Expect::Reject { .. })))
    }

    /// Everything the variant writes before its first call, in order: the
    /// main image, then `init`, then the log's empty pointer.
    pub fn boot(&self) -> Vec<(u32, Vec<u8>)> {
        let main = self.main_image();
        let mut out = vec![(main.base, main.bytes.clone())];
        out.extend(self.init.iter().cloned());
        let mut log = vec![0u8; self.layout.log_range().len()];
        log[..4].copy_from_slice(&(self.layout.log + 4).to_le_bytes());
        out.push((self.layout.log, log));
        out
    }
}

/// What a checkpoint saw.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
#[serde(tag = "kind", rename_all = "kebab-case")]
pub enum Outcome {
    Returned { v0: u32, v1: u32 },
    /// Suspended by a thread switch.
    Suspended,
    /// An explicit diagnostic of the port.
    Rejected { diag: String },
    /// Anything else: a generic trap, fuel exhausted, a host error.
    Failed { why: String },
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct Observation {
    pub outcome: Outcome,
    pub log: Vec<u32>,
}

/// Decode the log from its bytes (pointer, entries).
pub fn decode_log(layout: &Layout, bytes: &[u8]) -> Vec<u32> {
    let word = |i: usize| bytes.get(4 * i..4 * i + 4).map_or(0, |b| u32::from_le_bytes([b[0], b[1], b[2], b[3]]));
    let n = word(0).wrapping_sub(layout.log + 4) / 4;
    (0..n.min(LOG_WORDS)).map(|i| word(1 + i as usize)).collect()
}
