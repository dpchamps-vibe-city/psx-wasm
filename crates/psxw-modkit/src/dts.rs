//! The editor's types for script mods (plans/M12 phase 2): `psx.d.ts`, the
//! mod API, and `game.d.ts`, generated from a snapshot (D55). Mods stay
//! plain JavaScript; `checkJs` and `tsc --noEmit` check them against these.
//! Each symbol's doc comment gives its declaration, source, container,
//! address and tier.

use crate::snapshot::{Signature, Snapshot, TypeDef, TypeExpr};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// The mod API (`web/script.js`), as globals of the game Worker.
pub const PSX_DTS: &str = r#"// The script mod API (psx-wasm plans/M12): `mod` and the types of what
// its factory gets. Generated by `psxw mod sdk`; game.d.ts declares `Game`.

type u8 = number;
type s8 = number;
type u16 = number;
type s16 = number;
type u32 = number;
type s32 = number;
type u64 = bigint;
type s64 = bigint;
type f32 = number;
type f64 = number;
/** A guest address. */
type ptr = number;

declare const PSXW_TARGET: unique symbol;
declare const PSXW_HOOK: unique symbol;

/** A game function: call it inside the game, or hook it. */
interface GameFn<F extends (...args: any[]) => any> {
  (...args: Parameters<F>): ReturnType<F>;
  readonly address: number;
  readonly container: string;
  readonly [PSXW_TARGET]: F;
}

/** A named hook point from the game's manifest: hooked with its kind only. */
interface PointTarget<K extends "before" | "after"> {
  readonly [PSXW_TARGET]: K;
}

type AfterResult<R> = [R] extends [void] ? undefined : R;

/** A hook's handlers: any of before, after, and one of replace or around. */
interface Handlers<F extends (...args: any[]) => any> {
  before?(...args: Parameters<F>): void;
  after?(result: AfterResult<ReturnType<F>>, ...args: Parameters<F>): void;
  replace?(...args: Parameters<F>): ReturnType<F>;
  /** `original()` with no arguments passes the call's own. */
  around?(original: (...args: Parameters<F> | []) => ReturnType<F>, ...args: Parameters<F>): ReturnType<F>;
}

interface Hook {
  readonly [PSXW_HOOK]: true;
}

/** The handlers a target takes: a function's, or a point's one kind. */
type HandlersOf<T> = T extends GameFn<infer F> ? Handlers<F> : T extends PointTarget<"after"> ? { after(): void } : { before(): void };

interface HookFn {
  <T extends GameFn<any> | PointTarget<"before"> | PointTarget<"after">>(target: T, handlers: HandlersOf<T>): Hook;
}

interface Mem {
  u8(address: number): u8;
  s8(address: number): s8;
  u16(address: number): u16;
  s16(address: number): s16;
  u32(address: number): u32;
  s32(address: number): s32;
  setU8(address: number, value: number): void;
  setS8(address: number, value: number): void;
  setU16(address: number, value: number): void;
  setS16(address: number, value: number): void;
  setU32(address: number, value: number): void;
  setS32(address: number, value: number): void;
  bytes(address: number, n: number): Uint8Array;
  setBytes(address: number, bytes: ArrayLike<number>): void;
}

/** An array in guest memory: elements by index. */
interface ArrayView<T> {
  [index: number]: T;
  readonly length: number;
  at(index: number): T;
  [Symbol.iterator](): Iterator<T>;
}

/** A record type: a view of one at any address. */
interface RecordType<T> {
  readonly name: string;
  readonly size: number;
  at(address: number): T;
}

type Width = "u8" | "s8" | "u16" | "s16" | "u32" | "s32";
type FieldSpec = Width | { type: Width; offset?: number };
type StructOf<T extends Record<string, FieldSpec>> = { [K in keyof T]: number };

interface DataPatch {
  /** An address (`game.addr.name`, plus an offset), or { container, address }. */
  target: number | { container: string; address: number };
  offset?: number;
  type: Width | "bytes" | "fnptr";
  value: number | number[] | ((...words: number[]) => unknown);
}

interface ModDefinition {
  id: string;
  version: string;
  load_after?: string[];
  hooks?: Hook[];
  data?: DataPatch[];
  /** Called from the console by name, inside the game. */
  commands?: Record<string, (...args: any[]) => unknown>;
  /** Once the mod is installed and the game has booted, inside the game. */
  init?(): void;
}

interface LoadedMod {
  id: string;
  kind: "script" | "wasm";
  version: string;
  hooks: string[];
  commands: string[];
}

interface Psx {
  readonly mem: Mem;
  /** A record type of the mod's own, for memory no decomp has typed. */
  struct<T extends Record<string, FieldSpec>>(fields: T): RecordType<StructOf<T>>;
  /** Hook without writing a mod; active from the next vblank. */
  hook<T extends GameFn<any> | PointTarget<"before"> | PointTarget<"after">>(target: T, handlers: HandlersOf<T>): { id: string; ready: Promise<string>; remove(): void };
  cmd(name: string, ...args: unknown[]): Promise<unknown>;
  run<R>(fn: () => R): Promise<R>;
  load(url: string): Promise<string>;
  reload(id: string): Promise<string>;
  unload(id: string): Promise<void>;
  mods(): LoadedMod[];
}

interface ModApi {
  game: Game;
  mem: Mem;
  hook: HookFn;
  log(...args: unknown[]): void;
  psx: Psx;
}

/** A script mod's default export. */
declare function mod(factory: (api: ModApi) => ModDefinition): unknown;

/** In the game Worker's console. */
declare const psx: Psx;
declare const game: Game;
"#;

/// Words TS won't take as parameter names.
const RESERVED: &[&str] = &[
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum", "export", "extends", "false",
    "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null", "return", "super", "switch", "this", "throw", "true",
    "try", "typeof", "var", "void", "while", "with", "let", "static", "yield", "await", "implements", "interface", "package", "private",
    "protected", "public",
];

fn ident(s: &str) -> bool {
    let mut b = s.bytes();
    b.next().is_some_and(|c| c.is_ascii_alphabetic() || c == b'_' || c == b'$') && b.all(|c| c.is_ascii_alphanumeric() || c == b'_' || c == b'$')
}

/// A record id as a TS name: `struct Tag` as `Tag`, `Parent.field` as
/// `Parent_field`.
pub fn record_name(id: &str) -> String {
    id.trim_start_matches("struct ").trim_start_matches("union ").replace(['.', ' '], "_")
}

struct Gen<'a> {
    s: &'a Snapshot,
}

impl Gen<'_> {
    /// A type as TS writes a value of it.
    fn ts(&self, t: &TypeExpr) -> String {
        match t {
            TypeExpr::Width(w) => match w.as_str() {
                "void" => "void".into(),
                "u8" | "s8" | "u16" | "s16" | "u32" | "s32" | "u64" | "s64" | "f32" | "f64" => w.clone(),
                _ => "number".into(),
            },
            TypeExpr::Ptr { .. } | TypeExpr::Fn { .. } => "ptr".into(),
            TypeExpr::Array { array, .. } => format!("ArrayView<{}>", self.ts(array)),
            TypeExpr::Record { record } => match self.s.types.get(record) {
                Some(TypeDef::Struct { .. } | TypeDef::Union { .. }) => record_name(record),
                _ => "unknown".into(),
            },
            TypeExpr::Named { named } => match self.s.types.get(named) {
                Some(TypeDef::Typedef { ty }) => self.ts(ty),
                Some(TypeDef::Enum { .. }) => "s32".into(),
                _ => "u32".into(),
            },
        }
    }

    /// A type as C spells it, for doc comments.
    fn c(&self, t: &TypeExpr) -> String {
        match t {
            TypeExpr::Width(w) => w.clone(),
            TypeExpr::Ptr { ptr } => format!("{} *", self.c(ptr)),
            TypeExpr::Array { array, count } => format!("{}[{count}]", self.c(array)),
            TypeExpr::Record { record } => record.clone(),
            TypeExpr::Named { named } => named.clone(),
            TypeExpr::Fn { .. } => "fn".into(),
        }
    }

    fn sig(&self, sig: &Signature) -> String {
        let mut seen = BTreeSet::new();
        let params: Vec<String> = sig
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| {
                let mut n = p.name.clone().filter(|n| ident(n)).unwrap_or_else(|| format!("p{i}"));
                if RESERVED.contains(&n.as_str()) {
                    n.push('_');
                }
                while !seen.insert(n.clone()) {
                    n.push('_');
                }
                format!("{n}: {}", self.ts(&p.ty))
            })
            .collect();
        let rest = if sig.variadic { if params.is_empty() { "...va: number[]".to_string() } else { ", ...va: number[]".to_string() } } else { String::new() };
        format!("({}{rest}) => {}", params.join(", "), self.ts(&sig.result))
    }
}

/// `game.d.ts` from a snapshot. `tiers`: each function's tier by
/// (container, address), for its doc comment.
pub fn game_dts(s: &Snapshot, tiers: &BTreeMap<(String, u32), String>, hash: &str) -> String {
    let g = Gen { s };
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `psxw mod sdk` from snapshot {hash} ({} {}). Don't edit:\n// regenerate it. Each symbol: its declaration, source, container, address, tier.\n",
        s.source.kind, s.source.version
    );
    // Names that name one thing only, as `game` exposes them.
    let mut count: BTreeMap<&str, usize> = BTreeMap::new();
    for n in s.functions.iter().flat_map(|f| f.names.iter().chain(&f.deprecated)).chain(s.globals.iter().flat_map(|g| g.names.iter().chain(&g.deprecated))) {
        *count.entry(n.as_str()).or_default() += 1;
    }
    let unique = |n: &str| count.get(n) == Some(&1) && ident(n);
    let reserved = ["addr", "points", "types", "at", "snapshot"];
    let _ = writeln!(out, "interface Game {{");
    let doc = |p: Option<&crate::snapshot::Provenance>, container: &str, address: u32, tier: Option<&String>, dep: Option<&str>| -> String {
        let mut parts = Vec::new();
        if let Some(t) = p.and_then(|p| p.text.as_deref()) {
            parts.push(format!("`{}`", t.replace('`', "'").replace("*/", "* /")));
        }
        // Where it comes from: the source (several merged), its file.
        let from: Vec<&str> = p.into_iter().flat_map(|p| [Some(p.source.as_str()).filter(|s| !s.is_empty()), p.file.as_deref()]).flatten().collect();
        if !from.is_empty() {
            parts.push(from.join(" "));
        }
        parts.push(format!("{container} 0x{address:08X}"));
        if let Some(t) = tier {
            parts.push(t.clone());
        }
        let mut d = format!("  /** {}", parts.join(" · "));
        if let Some(new) = dep {
            d += &format!(" @deprecated renamed {new}");
        }
        d + " */"
    };
    for f in &s.functions {
        let ty = match &f.signature {
            Some(sig) => format!("GameFn<{}>", g.sig(sig)),
            None => "GameFn<(...words: number[]) => number>".into(),
        };
        let p = f.provenance.as_ref();
        let tier = tiers.get(&(f.container.clone(), f.address));
        for (i, n) in f.names.iter().enumerate().map(|(i, n)| (i, Some(n))).chain(f.deprecated.iter().map(|n| (usize::MAX, Some(n)))) {
            let Some(n) = n else { continue };
            if !unique(n) || reserved.contains(&n.as_str()) {
                continue;
            }
            let dep = (i == usize::MAX).then_some(f.names[0].as_str());
            let _ = writeln!(out, "{}", doc(p, &f.container, f.address, tier, dep));
            let _ = writeln!(out, "  {n}: {ty};");
        }
    }
    for gl in &s.globals {
        let Some(t) = &gl.ty else { continue };
        let p = gl.provenance.as_ref();
        for (i, n) in gl.names.iter().enumerate().map(|(i, n)| (i, n)).chain(gl.deprecated.iter().map(|n| (usize::MAX, n))) {
            if !unique(n) || reserved.contains(&n.as_str()) {
                continue;
            }
            let dep = (i == usize::MAX).then_some(gl.names[0].as_str());
            let _ = writeln!(out, "{}", doc(p, &gl.container, gl.address, None, dep));
            let _ = writeln!(out, "  {n}: {};", g.ts(t));
        }
    }
    let _ = writeln!(out, "  /** Globals' and functions' addresses. */\n  readonly addr: GameAddr;");
    let _ = writeln!(out, "  /** The manifest's hook points. */\n  readonly points: GamePoints;");
    let _ = writeln!(out, "  /** Record types: a view of one at any address. */\n  readonly types: GameTypes;");
    let _ = writeln!(out, "  /** A function by container and address, or by name in a container. */\n  at(container: string, where: number | string): GameFn<(...words: number[]) => number>;");
    let _ = writeln!(out, "  readonly snapshot: unknown;\n}}\n");

    let _ = writeln!(out, "interface GameAddr {{");
    let mut seen = BTreeSet::new();
    for n in s.globals.iter().flat_map(|g| g.names.iter().chain(&g.deprecated)).chain(s.functions.iter().flat_map(|f| f.names.iter())) {
        if unique(n) && seen.insert(n.clone()) {
            let _ = writeln!(out, "  readonly {n}: number;");
        }
    }
    let _ = writeln!(out, "  /** splat's auto-names resolve by their address. */\n  readonly [name: `D_${{string}}` | `func_${{string}}`]: number;\n}}\n");

    let _ = writeln!(out, "interface GamePoints {{");
    for (name, p) in &s.points {
        let kind = if p.before.is_some() { "before" } else { "after" };
        let of = p.before.as_deref().or(p.after.as_deref()).unwrap_or("");
        if let Some(d) = &p.doc {
            let _ = writeln!(out, "  /** {kind} {of}: {} */", d.replace("*/", "* /"));
        }
        let _ = writeln!(out, "  readonly {name}: PointTarget<\"{kind}\">;");
    }
    let _ = writeln!(out, "}}\n");

    let records: BTreeMap<String, &String> = s
        .types
        .iter()
        .filter(|(_, d)| matches!(d, TypeDef::Struct { .. } | TypeDef::Union { .. }))
        .map(|(id, _)| (record_name(id), id))
        .collect();
    let _ = writeln!(out, "interface GameTypes {{");
    for name in records.keys() {
        if ident(name) {
            let _ = writeln!(out, "  {name}: RecordType<{name}>;");
        }
    }
    for (id, d) in &s.types {
        if let TypeDef::Typedef { ty: TypeExpr::Record { record } } = d {
            let r = record_name(record);
            if ident(id) && !records.contains_key(id.as_str()) && records.contains_key(&r) {
                let _ = writeln!(out, "  {id}: RecordType<{r}>;");
            }
        }
    }
    let _ = writeln!(out, "}}\n");

    for (name, id) in &records {
        if !ident(name) {
            continue;
        }
        let (TypeDef::Struct { size, fields, provenance, .. } | TypeDef::Union { size, fields, provenance, .. }) = &s.types[*id] else { continue };
        let from = provenance.as_ref().and_then(|p| p.file.as_deref()).map(|f| format!(" · {f}")).unwrap_or_default();
        let _ = writeln!(out, "/** `{id}` · {size} bytes{from} */\ninterface {name} {{");
        for f in fields {
            if !ident(&f.name) {
                continue;
            }
            let _ = writeln!(out, "  /** +0x{:02X} `{}` */\n  {}: {};", f.offset, g.c(&f.ty), f.name, g.ts(&f.ty));
        }
        let _ = writeln!(out, "}}\n");
    }
    out
}
