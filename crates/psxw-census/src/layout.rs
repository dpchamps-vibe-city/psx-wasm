//! SDK struct layouts for the adapters (M8 task 4): the structs the
//! boundary's `[layout]` names, probed in the game's SDK headers with the
//! matching compiler and with clang for wasm32 (`psxw_cc::probe`, as the
//! census does). Only values both compilers agree on are kept; a struct
//! whose layout differs, or that no header defines, is an error.

use crate::checks::include_contexts;
use anyhow::{Result, bail};
use psxw_cc::Clang;
use psxw_cc::probe::{Outcome, Reference, probe_header};
use psxw_inputs::{AddressMap, Workspace, snapshot};
use serde::Serialize;
use std::collections::BTreeMap;

#[derive(Debug, Clone, Serialize)]
pub struct StructLayout {
    pub name: String,
    pub header: String,
    pub size: u32,
    pub align: u32,
    /// (field, byte offset), in declaration order.
    pub fields: Vec<(String, u32)>,
}

/// Layouts of `structs`, looked up in `headers` (paths under the game's
/// probe include dirs, e.g. `psyq/libgpu.h`).
pub fn sdk_layout(ws: &Workspace, game: &str, headers: &[String], structs: &[String]) -> Result<Vec<StructLayout>> {
    let manifest = ws.game(game)?;
    let pin = ws.game_pin(&manifest)?;
    let snap = snapshot::ensure(ws, &manifest.game.input, pin)?;
    let map = AddressMap::load(&snap, &manifest)?;
    let checkout = ws.checkout(pin);
    let tool = |p: &std::path::Path| if p.components().count() > 1 { checkout.join(p) } else { p.to_path_buf() };
    let reference = Reference {
        cpp: tool(&manifest.reference.cpp),
        cppflags: manifest.reference.cppflags.clone(),
        cc1: tool(&manifest.reference.cc1),
        cc1flags: manifest.reference.cc1flags.clone(),
    };
    let out = ws.out_dir().join("layout").join(game);
    let clang = Clang::new(ws.clang()?, snap.clone(), manifest.c.include.clone(), manifest.c.defines.clone(), &out)?;
    let contexts = include_contexts(&snap, &map);
    let dir = manifest.probe.include_dirs.first().map(|d| d.to_string_lossy().into_owned()).unwrap_or_else(|| "include".into());

    let mut found: BTreeMap<String, StructLayout> = BTreeMap::new();
    for h in headers {
        let prelude = contexts.get(h).unwrap_or(&manifest.probe.prelude);
        let entries = match probe_header(&clang, &reference, prelude, &dir, h, &out.join("probe"))? {
            Outcome::Probed { entries, .. } => entries,
            Outcome::Skipped(why) | Outcome::ClangFailed(why) => bail!("{h}: {why}"),
        };
        let wanted: Vec<&String> = structs.iter().filter(|s| !found.contains_key(*s)).collect();
        for s in wanted {
            let mine: Vec<_> = entries.iter().filter(|e| &e.entry.ty == s).collect();
            if mine.is_empty() {
                continue;
            }
            let value = |expr: &str| -> Result<u32> {
                let e = mine.iter().find(|e| e.entry.expr == expr).ok_or_else(|| anyhow::anyhow!("{s}: no probe for {expr}"))?;
                match (e.reference, e.clang) {
                    (Some(a), Some(b)) if a == b => Ok(a),
                    (a, b) => bail!("{s}: {expr} is {a:?} under the reference compiler and {b:?} under clang"),
                }
            };
            let mut fields = Vec::new();
            for e in mine.iter().filter(|e| e.entry.field.is_some()) {
                fields.push((e.entry.field.clone().unwrap_or_default(), value(&e.entry.expr)?));
            }
            found.insert(
                s.clone(),
                StructLayout { name: s.clone(), header: h.clone(), size: value(&format!("sizeof({s})"))?, align: value(&format!("__alignof__({s})"))?, fields },
            );
        }
    }
    let missing: Vec<&String> = structs.iter().filter(|s| !found.contains_key(*s)).collect();
    if !missing.is_empty() {
        bail!("no header among {headers:?} defines {missing:?}");
    }
    Ok(structs.iter().filter_map(|s| found.remove(s)).collect())
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 && name[..i].chars().last().is_some_and(|p| p.is_ascii_lowercase()) {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}

/// The Rust module: one `pub mod` per struct with `SIZEOF`, `ALIGNOF` and
/// a constant per field.
pub fn rust_module(layouts: &[StructLayout], provenance: &str) -> String {
    let mut s = String::new();
    s += "//! SDK struct layouts for the adapters. Generated by `psxw layout`; do\n";
    s += "//! not edit. Byte offsets and sizes, equal under the matching compiler\n";
    s += "//! (GCC 2.95, MIPS o32) and clang (wasm32).\n//!\n";
    for l in provenance.lines() {
        s += &format!("//! {l}\n");
    }
    for l in layouts {
        s += &format!("\n/// `{}` ({}).\npub mod {} {{\n", l.name, l.header, snake(&l.name));
        s += &format!("    pub const SIZEOF: u32 = {};\n    pub const ALIGNOF: u32 = {};\n", l.size, l.align);
        for (f, off) in &l.fields {
            s += &format!("    pub const {}: u32 = {off};\n", f.to_ascii_uppercase());
        }
        s += "}\n";
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_shape() {
        let l = StructLayout { name: "SpuVoiceAttr".into(), header: "psyq/libspu.h".into(), size: 64, align: 4, fields: vec![("voice".into(), 0), ("mask".into(), 4)] };
        let m = rust_module(&[l], "test");
        assert!(m.contains("pub mod spu_voice_attr {"));
        assert!(m.contains("pub const MASK: u32 = 4;"));
        assert_eq!(snake("DRAWENV"), "drawenv");
        assert_eq!(snake("CdlLOC"), "cdl_loc");
    }
}
